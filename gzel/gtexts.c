c8 * gzel_hex_to_binary(i32 hex_val)
{   
    u8 count;
    if (hex_val <= 0xFF) {            // 1 byte
        count = 8;
    } else if (hex_val <= 0xFFFF) {   // 2 bytes
        count = 16;
    } else if (hex_val <= 0xFFFFFF) { // 3 bytes
        count = 24;
    } else {                          // 4 bytes
        count = 32;
    }

    static c8 buf[ 33 ];

    for (i32 i = 0; i < count; i++) {
        if(count == 8)  buf[i] = (hex_val & (0x80 >> i)) ? '#' : '.';
        if(count == 16) buf[i] = (hex_val & (0x8000 >> i)) ? '#' : '.';
        if(count == 24) buf[i] = (hex_val & (0x800000 >> i)) ? '#' : '.';
        if(count == 32) buf[i] = (hex_val & (0x80000000 >> i)) ? '#' : '.';
    }
    buf[ count ] = '\0';

    return buf;
}

void gzel_draw_text(const c8 *text, u16 pos_x, u16 pos_y, u16 font_size, color col)
{
    if(font_size >= 8) font_size = font_size /8;
    else font_size = 1;
    
    u16 len = strlen(text);
    u8 idx;

    for (u16 i = 0; i < len; i++){
        if (text[i] >= 65 && text[i] <= 90){ // Uppercase letters "A-Z"
            idx = text[i] - 65;
        }
        if (text[i] >= 97 && text[i] <= 122){ // Lowercase letters "a-z"
            idx = text[i] - 97;
        }
        if (!(text[i] == ' ')){
            // DRAW A CHAR
            c8 * buf;
            for (u8 j = 0; j < 8 ; j++){
                buf = gzel_hex_to_binary(FONT_8X8[idx][j]);
                for (u8 k = 0; k < 8; k++){
                    if (buf[k] == '#') {
                        gzel_box(pos_x + (k * font_size) + (i * 8 * font_size), pos_y + (j * font_size), font_size, font_size , col);
                    }
                }
            }
        }
    }
}
